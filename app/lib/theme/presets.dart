// Colour themes as data: each preset is a day (light) and an evening (dark) set of role colours.
// app_theme.dart turns one into ThemeData; screens read the ColorScheme and FamTokens, never these.
// Error and presence colours are shared by every preset (see app_theme.dart). Every preset must
// pass test/theme/contrast_test.dart: text on every surface and bubble at 4.5:1 or better.
import 'dart:ui' show Color;

import 'palette.dart';

/// The role colours of one preset in one brightness. Field names follow the ColorScheme slot or
/// FamTokens token each one fills.
class PresetColors {
  const PresetColors({
    required this.primary,
    required this.onPrimary,
    required this.primaryContainer,
    required this.onPrimaryContainer,
    required this.secondary,
    required this.onSecondary,
    required this.secondaryContainer,
    required this.onSecondaryContainer,
    required this.tertiary,
    required this.onTertiary,
    required this.tertiaryContainer,
    required this.onTertiaryContainer,
    required this.surface,
    required this.onSurface,
    required this.onSurfaceVariant,
    required this.surfaceDim,
    required this.surfaceBright,
    required this.surfaceContainerLowest,
    required this.surfaceContainerLow,
    required this.surfaceContainer,
    required this.surfaceContainerHigh,
    required this.surfaceContainerHighest,
    required this.outline,
    required this.outlineVariant,
    required this.inverseSurface,
    required this.onInverseSurface,
    required this.inversePrimary,
    required this.mineBubble,
    required this.mineBubbleEnd,
    required this.onMineBubble,
    required this.mineMeta,
    required this.theirsBubble,
    required this.theirsBorder,
    required this.chatBackdrop,
  });

  /// Brand ink in the day (buttons, the inverse surface); the own-message colour in the evening.
  final Color primary, onPrimary, primaryContainer, onPrimaryContainer;

  /// The own-message accent: [secondaryContainer] is its fill, [secondary] a version text can use.
  final Color secondary, onSecondary, secondaryContainer, onSecondaryContainer;

  /// Links, focus rings, selection: the quiet accent.
  final Color tertiary, onTertiary, tertiaryContainer, onTertiaryContainer;

  /// The rooms: [surface] is the page; the containers step up from it.
  final Color surface, surfaceDim, surfaceBright;
  final Color surfaceContainerLowest, surfaceContainerLow, surfaceContainer;
  final Color surfaceContainerHigh, surfaceContainerHighest;

  /// Body text and muted text, on every surface.
  final Color onSurface, onSurfaceVariant;

  /// [outline] for control borders, [outlineVariant] for hairlines.
  final Color outline, outlineVariant;

  final Color inverseSurface, onInverseSurface, inversePrimary;

  /// Your own messages: a gradient from [mineBubble] (top left) to [mineBubbleEnd] (bottom right).
  /// The unread badge wears [mineBubble]. Text must read on both ends.
  final Color mineBubble, mineBubbleEnd, onMineBubble, mineMeta;

  /// Everyone else's messages, and the room behind the conversation.
  final Color theirsBubble, theirsBorder, chatBackdrop;
}

