// Writes test/crypto/vectors_v1.dart from the fixed inputs in test/crypto/vector_inputs.dart.
// Run from app/: dart run tool/gen_crypto_vectors.dart
// Only regenerate for a deliberate format change, and bump the format version when you do.
import 'dart:convert';
import 'dart:io';

import '../test/crypto/vector_inputs.dart';

Future<void> main() async {
  final vectors = await (await VectorInputs.load()).compute();
  final b = StringBuffer()
    ..writeln('// GENERATED by `dart run tool/gen_crypto_vectors.dart` from test/crypto/vector_inputs.dart.')
    ..writeln('// Do not edit. These pin the v1 wire formats; a change here is a format change.')
    ..writeln('const Map<String, String> vectorsV1 = {');
  for (final e in vectors.entries) {
    b.writeln('  ${jsonEncode(e.key)}:');
    b.writeln("      r'${e.value}',");
  }
  b.writeln('};');
  final out = File('test/crypto/vectors_v1.dart');
  await out.writeAsString(b.toString());
  stdout.writeln('wrote ${out.path} (${vectors.length} vectors)');
}
