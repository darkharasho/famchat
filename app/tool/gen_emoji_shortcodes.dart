// Generates lib/chat/emoji/shortcode_data.dart from GitHub's gemoji database (MIT licence):
// https://github.com/github/gemoji/blob/master/db/emoji.json
//
//   curl -sSfL -o /tmp/emoji.json https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json
//   dart run tool/gen_emoji_shortcodes.dart /tmp/emoji.json <gemoji commit>
//
// gemoji names are the ones GitHub, Slack and Discord share (`+1`, `thumbsup`, `heart`, `joy`, `tada`, …).
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln('usage: dart run tool/gen_emoji_shortcodes.dart <emoji.json> <gemoji commit>');
    exit(2);
  }
  final entries = (jsonDecode(File(args[0]).readAsStringSync()) as List).cast<Map<String, dynamic>>();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_emoji_shortcodes.dart. Do not edit by hand.')
    ..writeln('// Source: github/gemoji db/emoji.json at ${args[1]} (MIT licence).')
    ..writeln()
    ..writeln('/// Shortcode name (without colons) → emoji, in gemoji order (Unicode category order).')
    ..writeln('const emojiShortcodes = <String, String>{');
  final seen = <String>{};
  for (final e in entries) {
    final emoji = e['emoji'] as String;
    for (final alias in (e['aliases'] as List).cast<String>()) {
      if (!RegExp(r'^[a-z0-9_+\-]+$').hasMatch(alias) || !seen.add(alias)) continue;
      out.writeln("  '$alias': '$emoji',");
    }
  }
  out.writeln('};');
  File('lib/chat/emoji/shortcode_data.dart')
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('${seen.length} shortcodes');
}
