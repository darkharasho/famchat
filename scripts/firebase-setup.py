#!/usr/bin/env python3
"""Helper for scripts/setup-firebase.sh. Two subcommands:

  apps   Makes sure the Firebase project has an Android, an iOS and a web app for FamChat, then writes
         app/lib/push/firebase_options.dart and app/web/firebase-config.js from their configs.
         (These identify the project; they are not secret and are committed.)
  key    Creates a new key for the project's firebase-adminsdk service account and stores it as the
         Worker secret FCM_SERVICE_ACCOUNT (`wrangler secret put`, run in server/). The key is
         handed over on stdin, never printed or written to disk; if storing fails, the new key is
         deleted again so no unheld key stays valid.

Uses the Firebase CLI (FIREBASE env: the command to run it) and its stored login.
"""
import base64
import json
import os
import plistlib
import re
import shlex
import subprocess
import sys
import urllib.error
import urllib.parse
import urllib.request

PROJECT = os.environ.get("FIREBASE_PROJECT", "famchat-da329")
BUNDLE_ID = "dev.famchat.app"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIREBASE = shlex.split(os.environ.get("FIREBASE", "npx -y firebase-tools"))


def log(msg):
    print(msg, file=sys.stderr)


def firebase(*args):
    out = subprocess.run([*FIREBASE, *args, "--project", PROJECT, "--json"], capture_output=True, text=True)
    try:
        body = json.loads(out.stdout)
    except json.JSONDecodeError:
        raise SystemExit(f"firebase {' '.join(args)} failed:\n{out.stderr.strip() or out.stdout.strip()}")
    if body.get("status") != "success":
        raise SystemExit(f"firebase {' '.join(args)} failed: {body.get('error', body)}")
    return body.get("result")


# --- apps -------------------------------------------------------------------------------------------


def ensure_app(apps, platform, create_args):
    mine = [a for a in apps if a.get("platform") == platform]
    for key in ("packageName", "bundleId"):
        exact = [a for a in mine if a.get(key) == BUNDLE_ID]
        if exact:
            return exact[0]["appId"]
    if mine:
        return mine[0]["appId"]
    log(f"creating the {platform} app in Firebase")
    created = firebase("apps:create", platform, *create_args)
    return created["appId"]


def sdk_config(platform, app_id):
    r = firebase("apps:sdkconfig", platform, app_id)
    if isinstance(r, dict) and isinstance(r.get("sdkConfig"), dict):
        return r["sdkConfig"]
    contents = r.get("fileContents", "") if isinstance(r, dict) else ""
    if platform == "ANDROID":
        j = json.loads(contents)
        client = next(
            (c for c in j["client"] if c["client_info"]["android_client_info"]["package_name"] == BUNDLE_ID),
            j["client"][0],
        )
        return {
            "apiKey": client["api_key"][0]["current_key"],
            "appId": client["client_info"]["mobilesdk_app_id"],
            "messagingSenderId": j["project_info"]["project_number"],
            "projectId": j["project_info"]["project_id"],
            "storageBucket": j["project_info"].get("storage_bucket"),
        }
    if platform == "IOS":
        p = plistlib.loads(contents.encode())
        return {
            "apiKey": p["API_KEY"],
            "appId": p["GOOGLE_APP_ID"],
            "messagingSenderId": p["GCM_SENDER_ID"],
            "projectId": p["PROJECT_ID"],
            "storageBucket": p.get("STORAGE_BUCKET"),
        }
    # Web: a JS snippet with an object literal.
    m = re.search(r"\{[^{}]*\}", contents)
    if not m:
        raise SystemExit("could not read the web app config")
    obj = re.sub(r"(\w+)\s*:", r'"\1":', m.group(0))
    return json.loads(obj)


def dart_options(name, c, extra=""):
    fields = [("apiKey", c["apiKey"]), ("appId", c["appId"]), ("messagingSenderId", str(c["messagingSenderId"])),
              ("projectId", c["projectId"])]
    for k in ("authDomain", "storageBucket", "measurementId"):
        if c.get(k):
            fields.append((k, c[k]))
    body = "".join(f"    {k}: {json.dumps(v)},\n" for k, v in fields)
    return f"  static const FirebaseOptions {name} = FirebaseOptions(\n{body}{extra}  );\n"


def cmd_apps():
    apps = firebase("apps:list") or []
    android = ensure_app(apps, "ANDROID", ["FamChat Android", "--package-name", BUNDLE_ID])
    ios = ensure_app(apps, "IOS", ["FamChat iOS", "--bundle-id", BUNDLE_ID])
    web = ensure_app(apps, "WEB", ["FamChat web"])
    a, i, w = sdk_config("ANDROID", android), sdk_config("IOS", ios), sdk_config("WEB", web)

    dart = (
        "// Generated by scripts/setup-firebase.sh (Firebase project " + PROJECT + "). These values identify the\n"
        "// project and aren't secret. Push runs on Android, iOS and the web; other platforms throw, which\n"
        "// turns push off there (desktop apps notify from their socket).\n"
        "import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;\n"
        "import 'package:flutter/foundation.dart' show defaultTargetPlatform, kIsWeb, TargetPlatform;\n\n"
        "class DefaultFirebaseOptions {\n"
        "  static FirebaseOptions get currentPlatform {\n"
        "    if (kIsWeb) return web;\n"
        "    return switch (defaultTargetPlatform) {\n"
        "      TargetPlatform.android => android,\n"
        "      TargetPlatform.iOS => ios,\n"
        "      _ => throw UnsupportedError('No push on this platform'),\n"
        "    };\n"
        "  }\n\n"
        + dart_options("web", w) + "\n"
        + dart_options("android", a) + "\n"
        + dart_options("ios", i, f"    iosBundleId: {json.dumps(BUNDLE_ID)},\n")
        + "}\n"
    )
    with open(os.path.join(ROOT, "app/lib/push/firebase_options.dart"), "w") as f:
        f.write(dart)
    web_keys = {k: w[k] for k in ("apiKey", "authDomain", "projectId", "storageBucket", "messagingSenderId", "appId") if w.get(k)}
    with open(os.path.join(ROOT, "app/web/firebase-config.js"), "w") as f:
        f.write(
            "// The Firebase web app's config for firebase-messaging-sw.js. Written by scripts/setup-firebase.sh;\n"
            "// null means push isn't set up. (These values identify the Firebase project; they aren't secret.)\n"
            f"self.famchatFirebaseConfig = {json.dumps(web_keys, indent=2)};\n"
        )
    log("wrote app/lib/push/firebase_options.dart and app/web/firebase-config.js")


