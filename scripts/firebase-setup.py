# The Firebase CLI's own OAuth client (public, shipped inside firebase-tools), used to turn its stored
# refresh token into an access token. Its login already has the cloud-platform scope.
CLI_CLIENT_ID = "563584335869-fgrhgmd47bqnekij5i8b5pr03ho849e6.apps.googleusercontent.com"
CLI_CLIENT_SECRET = "j9iVZfS8kkCEFUPaAeJV0sAi"


def access_token():
    firebase("projects:list")  # refreshes the stored login if needed
    path = os.path.expanduser("~/.config/configstore/firebase-tools.json")
    with open(path) as f:
        tokens = json.load(f).get("tokens", {})
    refresh = tokens.get("refresh_token")
    if not refresh:
        raise SystemExit("no Firebase CLI login found; run `firebase login` first")
    data = urllib.parse.urlencode({
        "grant_type": "refresh_token", "refresh_token": refresh,
        "client_id": CLI_CLIENT_ID, "client_secret": CLI_CLIENT_SECRET,
    }).encode()
    with urllib.request.urlopen("https://oauth2.googleapis.com/token", data) as r:
        return json.load(r)["access_token"]


def google(method, url, token, body=None):
    req = urllib.request.Request(url, method=method, headers={"authorization": f"Bearer {token}", "content-type": "application/json"},
                                 data=None if body is None else json.dumps(body).encode())
    try:
        with urllib.request.urlopen(req) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        raise SystemExit(f"{method} {url.split('?')[0]} failed: {e.code} {e.read().decode()[:400]}")


def cmd_key():
    token = access_token()
    # FCM HTTP v1 is on for new projects; make sure.
    try:
        google("POST", f"https://serviceusage.googleapis.com/v1/projects/{PROJECT}/services/fcm.googleapis.com:enable", token, {})
    except SystemExit as e:
        log(f"note: could not enable the FCM API ({e}); it is usually on already")
    accounts = google("GET", f"https://iam.googleapis.com/v1/projects/{PROJECT}/serviceAccounts", token).get("accounts", [])
    admin = next((a["email"] for a in accounts if a["email"].startswith("firebase-adminsdk-")), None)
    if not admin:
        raise SystemExit("no firebase-adminsdk service account in the project")
    base = f"https://iam.googleapis.com/v1/projects/{PROJECT}/serviceAccounts/{admin}/keys"
    older = google("GET", base + "?keyTypes=USER_MANAGED", token).get("keys", [])
    log(f"creating a key for {admin}")
    key = google("POST", base, token, {})
    secret = base64.b64decode(key["privateKeyData"])
    put = subprocess.run(["npx", "wrangler", "secret", "put", "FCM_SERVICE_ACCOUNT"], input=secret, cwd=os.path.join(ROOT, "server"))
    del secret
    if put.returncode != 0:
        google("DELETE", f"https://iam.googleapis.com/v1/{key['name']}", token)
        raise SystemExit("wrangler secret put failed; the new key was deleted again")
    log("stored FCM_SERVICE_ACCOUNT")
    if older:
        log(f"note: {admin} has {len(older)} older key(s). If none is used elsewhere, delete them at\n"
            f"  https://console.cloud.google.com/iam-admin/serviceaccounts?project={PROJECT}")


if __name__ == "__main__":
    {"apps": cmd_apps, "key": cmd_key}.get(sys.argv[1] if len(sys.argv) > 1 else "", lambda: sys.exit(__doc__))()
